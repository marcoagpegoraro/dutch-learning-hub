export function buildArticleQuestions(nouns = articleNouns): MultipleChoiceQuestion[] {
  return nouns.map((item) => ({
    id: `articles-${item.id}`,
    moduleId: 'articles',
    difficulty: item.difficulty,
    type: 'multiple-choice',
    prompt: `${item.emoji} ___ ${item.noun} (${item.meaning})`,
    dutchAudio: item.noun,
    dutchAnswerAudio: `${item.article} ${item.noun}. ${item.example}`,
    options: ['de', 'het'],
    correctOption: item.article,
    hint:
      item.difficulty === 'easy'
        ? `Say “${item.article} ${item.noun}” aloud as one phrase.`
        : item.note,
    explanation: `${item.example} ${item.plural === '—' ? 'This noun normally has no regular plural.' : `Plural: de ${item.plural}.`} ${item.note}`,
    tags: ['article', item.article],
  }));
}
