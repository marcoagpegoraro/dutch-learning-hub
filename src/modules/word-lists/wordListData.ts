export interface WordListEntry {
  id: string;
  dutch: string;
  portuguese: string;
}

export interface WordList {
  id: string;
  title: string;
  description: string;
  entries: WordListEntry[];
  kind: 'starter' | 'custom';
}

type EntryTuple = readonly [dutch: string, portuguese: string];

function entries(listId: string, words: readonly EntryTuple[]): WordListEntry[] {
  return words.map(([dutch, portuguese], index) => ({
    id: `${listId}-${index + 1}`,
    dutch,
    portuguese,
  }));
}

function starter(
  id: string,
  title: string,
  description: string,
  words: readonly EntryTuple[],
): WordList {
  return { id, title, description, entries: entries(id, words), kind: 'starter' };
}

