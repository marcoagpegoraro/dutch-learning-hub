export type NegationContext =
  'indefinite-noun' | 'plural-indefinite' | 'verb' | 'adjective' | 'definite-noun' | 'proper-noun';

export function chooseNegation(context: NegationContext): 'niet' | 'geen' {
  return context === 'indefinite-noun' || context === 'plural-indefinite' ? 'geen' : 'niet';
}

