"""Generate Dutch synthetic course assets with installed macOS voices. No network calls."""
import concurrent.futures,hashlib,json,subprocess,tempfile,wave
from pathlib import Path
root=Path(__file__).resolve().parent.parent
units=json.loads((root/'src/modules/a2/a2Content.json').read_text())
jobs=[]
for unit in units:
 for case in unit['cases']:
  jobs.extend((audio['file'],audio['segments']) for audio in case['audios'])
  jobs.extend((turn['file'],[dict(voice='Xander',text=turn['prompt'])]) for turn in case['dialogue'])
manifest_path=root/'public/audio/a2/manifest.json'
previous=json.loads(manifest_path.read_text()).get('assets',{}) if manifest_path.exists() else {}
def generate(job):
 file,segments=job
 digest=hashlib.sha256(json.dumps(segments,ensure_ascii=False).encode()).hexdigest()
 target=root/'public'/file
 if target.exists() and target.stat().st_size>1000 and previous.get(file,{}).get('scriptHash')==digest:return file,previous[file]
 with tempfile.TemporaryDirectory(prefix='dutch-a2-') as temp:
  tmp=Path(temp);frames=[];duration=0
  for i,segment in enumerate(segments):
   script=tmp/f'{i}.txt';script.write_text(segment['text'])
   output=tmp/f'{i}.wav'
   subprocess.run(['say','-v',segment['voice'],'-r','145','--file-format=WAVE','--data-format=LEI16@22050','-f',str(script),'-o',str(output)],check=True,capture_output=True)
   with wave.open(str(output)) as w:
    if w.getnframes()<100:raise RuntimeError('Empty speech output; run this helper with access to system speech services.')
    frames.extend([w.readframes(w.getnframes()),b'\x00'*(22050//3)*2]);duration+=w.getnframes()/22050+1/3
  combined=tmp/'combined.wav'
  with wave.open(str(combined),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(22050);w.writeframes(b''.join(frames))
  target.parent.mkdir(parents=True,exist_ok=True)
  subprocess.run(['afconvert','-f','m4af','-d','aac','-b','48000',str(combined),str(target)],check=True,capture_output=True)
  if target.stat().st_size<1000:raise RuntimeError(f'Empty converted audio: {file}')
  return file,dict(scriptHash=digest,voices=sorted(set(s['voice'] for s in segments)),durationSeconds=round(duration,2),bytes=target.stat().st_size)
assets={}
with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool:
 for n,(file,info) in enumerate(pool.map(generate,jobs),1):
  assets[file]=info
  if n%15==0:print(f'{n}/{len(jobs)} Dutch audio assets ready',flush=True)
manifest_path.write_text(json.dumps(dict(kind='synthetic-dutch-course-audio',linguisticReview='pending',voices={'Xander':'nl-NL','Ellen':'nl-BE'},assets=assets),ensure_ascii=False,indent=2)+'\n')
print(f'Validated {len(assets)} assets, {sum(v["bytes"] for v in assets.values())/1024/1024:.1f} MB',flush=True)

version=hashlib.sha256(json.dumps(assets,sort_keys=True).encode()).hexdigest()[:12]
(root/'src/modules/a2/audioVersion.ts').write_text(f"// Generated by scripts/generate-a2-audio.py.\nexport const A2_AUDIO_VERSION = '{version}';\n")
